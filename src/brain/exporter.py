"""
exporter.py — Markdown export utility for Brain CLI output.

Every CLI command that produces output can pipe through here
when the --export flag is set.

Output convention:
  exports/<sensitivity>/YYYY-MM-DD_<command>_<slug>.md

The export file is a clean, self-contained markdown document —
human readable, version control friendly (public exports only).
"""

import re
from datetime import date, datetime
from pathlib import Path

from brain.config import BrainConfig

# ── Markdown Template ─────────────────────────────────────────────────────────

EXPORT_TEMPLATE = """\
---
title: "{title}"
command: "{command}"
scope: "{scope}"
sensitivity: "{sensitivity}"
exported_at: "{exported_at}"
query: "{query}"
date_range: "{date_range}"
---

# {title}

> **Command:** `{command}`
> **Exported:** {exported_at}
{query_line}
{date_range_line}
---

{content}

---
*Generated by Brain — local personal second brain*
"""


# ── Exporter ──────────────────────────────────────────────────────────────────


class Exporter:
    """
    Writes CLI output to a dated, organised markdown file.

    Responsibilities:
    - Determine correct output directory (public vs sensitive)
    - Generate a clean, collision-safe filename
    - Wrap content in a structured markdown template
    - Ensure output directories exist before writing
    """

    def __init__(self, config: BrainConfig | None = None):
        self.config = config or BrainConfig()

    def export(
        self,
        content: str,
        command: str,
        sensitivity: str,
        title: str | None = None,
        query: str | None = None,
        date_from: str | None = None,
        date_to: str | None = None,
        scope: str = "all",
    ) -> Path:
        """
        Write content to a markdown export file.

        Args:
            content:     The main body text to export
            command:     CLI command name e.g. "query", "summarize", "trend"
            sensitivity: "public" or "sensitive" — determines output directory
            title:       Human readable title (auto-generated if not provided)
            query:       Original query string if applicable
            date_from:   Start date for range queries (YYYY-MM-DD)
            date_to:     End date for range queries (YYYY-MM-DD)
            scope:       Query scope e.g. "public", "sensitive", "all"

        Returns:
            Path to the written export file
        """
        self._validate_sensitivity(sensitivity)

        # ── Build file components ─────────────────────────────────────────────
        export_date = date.today().isoformat()
        exported_at = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        title = title or self._auto_title(command, query, date_from, date_to)
        slug = self._make_slug(query or title)
        filename = f"{export_date}_{command}_{slug}.md"

        # ── Resolve output path ───────────────────────────────────────────────
        output_dir = self.config.exports_path_for(sensitivity)
        output_dir.mkdir(parents=True, exist_ok=True)
        output_path = output_dir / filename

        # ── Handle filename collision (rare but possible) ─────────────────────
        output_path = self._resolve_collision(output_path)

        # ── Render template ───────────────────────────────────────────────────
        date_range = self._format_date_range(date_from, date_to)
        markdown = EXPORT_TEMPLATE.format(
            title=title,
            command=command,
            scope=scope,
            sensitivity=sensitivity,
            exported_at=exported_at,
            query=query or "",
            date_range=date_range,
            query_line=f"> **Query:** {query}\n" if query else "",
            date_range_line=f"> **Date Range:** {date_range}\n" if date_range else "",
            content=content.strip(),
        )

        # ── Write file ────────────────────────────────────────────────────────
        output_path.write_text(markdown, encoding="utf-8")
        return output_path

    # ── Private Helpers ───────────────────────────────────────────────────────

    def _validate_sensitivity(self, sensitivity: str) -> None:
        if sensitivity not in ("public", "sensitive"):
            raise ValueError(
                f"Invalid sensitivity '{sensitivity}'. Use 'public' or 'sensitive'."
            )

    def _auto_title(
        self,
        command: str,
        query: str | None,
        date_from: str | None,
        date_to: str | None,
    ) -> str:
        """Generate a readable title when none is provided."""
        if query:
            # Truncate long queries for title
            short_query = query[:60] + "..." if len(query) > 60 else query
            return f"{command.title()}: {short_query}"
        if date_from and date_to:
            return f"{command.title()}: {date_from} to {date_to}"
        if date_from:
            return f"{command.title()}: from {date_from}"
        return f"{command.title()} Export"

    def _make_slug(self, text: str) -> str:
        """
        Convert text to a safe filename slug.
        e.g. "What was I blocked on?" → "what-was-i-blocked-on"
        """
        # Lowercase, replace non-alphanumeric with hyphens
        slug = text.lower().strip()
        slug = re.sub(r"[^\w\s-]", "", slug)  # remove special chars
        slug = re.sub(r"[\s_]+", "-", slug)  # spaces to hyphens
        slug = re.sub(r"-+", "-", slug)  # collapse multiple hyphens
        slug = slug.strip("-")  # trim leading/trailing hyphens
        # Truncate to keep filenames sane
        return slug[:50]

    def _format_date_range(
        self,
        date_from: str | None,
        date_to: str | None,
    ) -> str:
        """Format date range for display, handling partial ranges."""
        if date_from and date_to:
            return f"{date_from} → {date_to}"
        if date_from:
            return f"from {date_from}"
        if date_to:
            return f"until {date_to}"
        return ""

    def _resolve_collision(self, path: Path) -> Path:
        """
        If a file already exists at this path, append a counter suffix.
        e.g. 2026-02-20_query_azure.md → 2026-02-20_query_azure_2.md
        """
        if not path.exists():
            return path

        stem = path.stem
        suffix = path.suffix
        parent = path.parent
        counter = 2

        while True:
            new_path = parent / f"{stem}_{counter}{suffix}"
            if not new_path.exists():
                return new_path
            counter += 1
